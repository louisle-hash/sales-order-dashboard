create or replace function app_private.current_user_role()
returns text
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select role_key
  from public.user_profiles
  where user_id = (select auth.uid())
    and is_active = true
  limit 1
$$;

create or replace function app_private.is_active_user()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select
    (select auth.uid()) is not null
    and exists (
      select 1
      from public.user_profiles
      where user_id = (select auth.uid())
        and is_active = true
    )
$$;

create or replace function app_private.has_any_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select
    (select auth.uid()) is not null
    and coalesce(app_private.current_user_role() = any(allowed_roles), false)
$$;

revoke all on function app_private.current_user_role() from public;
revoke all on function app_private.is_active_user() from public;
revoke all on function app_private.has_any_role(text[]) from public;
grant usage on schema app_private to authenticated;
grant execute on function app_private.current_user_role() to authenticated;
grant execute on function app_private.is_active_user() to authenticated;
grant execute on function app_private.has_any_role(text[]) to authenticated;

create or replace function app_private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  insert into public.user_profiles (
    user_id,
    email,
    full_name,
    role_key,
    is_active
  )
  values (
    new.id,
    new.email,
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    'viewer',
    true
  )
  on conflict (user_id) do update
  set email = excluded.email,
      updated_at = now();
  return new;
end;
$$;

revoke all on function app_private.handle_new_auth_user() from public;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert or update of email on auth.users
for each row execute function app_private.handle_new_auth_user();

