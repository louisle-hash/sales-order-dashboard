-- ---------------------------------------------------------------------------
-- Updated-at triggers
-- ---------------------------------------------------------------------------

do $$
declare
  target_table text;
begin
  foreach target_table in array array[
    'user_profiles',
    'business_units',
    'warehouses',
    'product_master',
    'item_master',
    'suppliers',
    'supplier_item_policy',
    'purchase_order_header',
    'bom_header',
    'forecast_version',
    'forecast_line'
  ]
  loop
    execute format(
      'drop trigger if exists %I on public.%I',
      target_table || '_touch_updated_at',
      target_table
    );
    execute format(
      'create trigger %I before update on public.%I for each row execute function app_private.touch_updated_at()',
      target_table || '_touch_updated_at',
      target_table
    );
  end loop;
end
$$;

